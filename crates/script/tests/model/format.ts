function main(workbook: ExcelScript.Workbook) {
  const sheet = workbook.getActiveWorksheet();
  const header = sheet.getRange("A1:C1");
  const format = header.getFormat();
  const font = format.getFont();
  const looks = () => [font.getBold(), font.getItalic(), font.getStrikethrough(), font.getUnderline()];
  eq(looks(), [false, false, false, "None"]);
  font.setBold(true);
  font.setItalic(true);
  font.setStrikethrough(true);
  font.setUnderline(ExcelScript.RangeUnderlineStyle.double);
  eq(looks(), [true, true, true, "Double"]);
  font.setUnderline(ExcelScript.RangeUnderlineStyle.single);
  font.setStrikethrough(false);
  throws(() => font.setUnderline(ExcelScript.RangeUnderlineStyle.singleAccountant), "ExcelScript.RangeUnderlineStyle.singleAccountant is not supported");
  eq(font.getColor(), "#000000");
  font.setColor("white");
  eq(font.getColor(), "#FFFFFF");
  throws(() => font.setColor("nocolor"), "invalid");
  eq(font.getName(), "Aptos Narrow");
  font.setName("Arial");
  eq(font.getName(), "Arial");
  eq(font.getSize(), 11);
  font.setSize(14);
  eq(font.getSize(), 14);
  sheet.getRange("A1").getFormat().getFont().setSize(9);
  eq(font.getSize(), null);
  eq(sheet.getRange("A1:B1").getFormat().getFont().getBold(), true);
  eq(sheet.getRange("A1:A2").getFormat().getFont().getBold(), null);

  const fill = format.getFill();
  eq(fill.getColor(), "#FFFFFF");
  fill.setColor("#4472C4");
  eq(fill.getColor(), "#4472C4");
  eq(sheet.getRange("A1:A2").getFormat().getFill().getColor(), "");
  sheet.getRange("B1").getFormat().getFill().clear();
  eq(sheet.getRange("B1").getFormat().getFill().getColor(), "#FFFFFF");

  eq(format.getHorizontalAlignment(), "General");
  format.setHorizontalAlignment(ExcelScript.HorizontalAlignment.centerAcrossSelection);
  eq(format.getHorizontalAlignment(), "CenterAcrossSelection");
  format.setHorizontalAlignment(ExcelScript.HorizontalAlignment.center);
  eq(format.getHorizontalAlignment(), ExcelScript.HorizontalAlignment.center);
  throws(() => format.setHorizontalAlignment(ExcelScript.HorizontalAlignment.distributed), "not supported");
  eq(format.getVerticalAlignment(), "Bottom");
  format.setVerticalAlignment(ExcelScript.VerticalAlignment.top);
  eq(format.getVerticalAlignment(), "Top");
  throws(() => format.setVerticalAlignment(ExcelScript.VerticalAlignment.justify), "not supported");
  eq(format.getWrapText(), false);
  format.setWrapText(true);
  eq(format.getWrapText(), true);
  eq(format.getShrinkToFit(), false);
  format.setShrinkToFit(true);
  eq(format.getShrinkToFit(), true);
  eq(format.getIndentLevel(), 0);
  format.setIndentLevel(2);
  eq(format.getIndentLevel(), 2);
  throws(() => format.setIndentLevel(300), "invalid");
  eq(format.getTextOrientation(), 0);
  format.setTextOrientation(45);
  eq(format.getTextOrientation(), 45);
  throws(() => format.setTextOrientation(180), "not supported");
  throws(() => format.setTextOrientation(100), "invalid");

  const body = sheet.getRange("A2:C4").getFormat();
  eq(body.getBorders().map(b => b.getSideIndex()), ["EdgeTop", "EdgeBottom", "EdgeLeft", "EdgeRight", "InsideVertical", "InsideHorizontal"]);
  const bottom = body.getRangeBorder(ExcelScript.BorderIndex.edgeBottom);
  const line = () => [bottom.getStyle(), bottom.getWeight(), bottom.getColor()];
  eq(line(), ["None", "Thin", "#000000"]);
  bottom.setStyle(ExcelScript.BorderLineStyle.continuous);
  eq(line(), ["Continuous", "Thin", "#000000"]);
  bottom.setWeight(ExcelScript.BorderWeight.thick);
  bottom.setColor("red");
  eq(line(), ["Continuous", "Thick", "#FF0000"]);
  bottom.setStyle(ExcelScript.BorderLineStyle.double);
  eq(bottom.getStyle(), "Double");
  bottom.setStyle(ExcelScript.BorderLineStyle.dash);
  eq(line(), ["Dash", "Thin", "#FF0000"]);
  throws(() => bottom.setWeight(ExcelScript.BorderWeight.medium), "not supported");
  throws(() => bottom.setStyle(ExcelScript.BorderLineStyle.dashDot), "ExcelScript.BorderLineStyle.dashDot is not supported");
  throws(() => body.getRangeBorder(ExcelScript.BorderIndex.diagonalUp), "diagonal");
  body.getRangeBorder(ExcelScript.BorderIndex.insideHorizontal).setStyle(ExcelScript.BorderLineStyle.dot);
  body.getRangeBorder(ExcelScript.BorderIndex.insideVertical).setColor("gray");
  body.getRangeBorder(ExcelScript.BorderIndex.edgeTop).setWeight(ExcelScript.BorderWeight.hairline);
  body.getRangeBorder(ExcelScript.BorderIndex.edgeLeft).setStyle(ExcelScript.BorderLineStyle.continuous);
  body.getRangeBorder(ExcelScript.BorderIndex.edgeRight).setWeight(ExcelScript.BorderWeight.medium);
  bottom.setStyle(ExcelScript.BorderLineStyle.none);
  eq(line(), ["None", "Thin", "#000000"]);

  near(format.getColumnWidth(), 48);
  format.setColumnWidth(90);
  near(format.getColumnWidth(), 90);
  sheet.getRange("A1").getFormat().setColumnWidth(30);
  eq(format.getColumnWidth(), null);
  near(format.getRowHeight(), 15);
  format.setRowHeight(30);
  near(format.getRowHeight(), 30);
  eq(sheet.getRange("A1:A2").getFormat().getRowHeight(), null);
  near(sheet.getRange("A2:A9").getFormat().getRowHeight(), 15);
  sheet.getRange("E1").setValue("A rather long piece of text");
  sheet.getRange("A:E").getFormat().autofitColumns();
  eq(sheet.getRange("E1").getFormat().getColumnWidth() > 60, true);
  eq(sheet.getRange("A1").getFormat().getColumnWidth() < 60, true);
  near(sheet.getRange("D1").getFormat().getColumnWidth(), 48);
  sheet.getRange("1:4").getFormat().autofitRows();
  eq(sheet.getRange("A1").getFormat().getRowHeight() > 15, true);
  near(sheet.getRange("A2").getFormat().getRowHeight(), 15);

  const lock = sheet.getRange("B2:B4").getFormat().getProtection();
  eq([lock.getLocked(), lock.getFormulaHidden()], [true, false]);
  lock.setLocked(false);
  lock.setFormulaHidden(true);
  eq([lock.getLocked(), lock.getFormulaHidden()], [false, true]);
}
