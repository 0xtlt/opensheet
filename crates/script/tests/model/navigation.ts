function main(workbook: ExcelScript.Workbook) {
  const sheet = workbook.getActiveWorksheet();
  const r = sheet.getRange("B2:C3");
  eq(r.getCell(0, 0).getAddress(), "Sheet1!B2");
  eq(r.getCell(2, 2).getAddress(), "Sheet1!D4");
  eq(r.getRow(1).getAddress(), "Sheet1!B3:C3");
  eq(r.getColumn(1).getAddress(), "Sheet1!C2:C3");
  eq(r.getEntireRow().getAddress(), "Sheet1!2:3");
  eq(r.getEntireColumn().getAddress(), "Sheet1!B:C");
  eq([r.getEntireRow().getIsEntireRow(), r.getIsEntireRow()], [true, false]);
  eq([r.getEntireColumn().getIsEntireColumn(), r.getIsEntireColumn()], [true, false]);
  eq(r.getOffsetRange(1, -1).getAddress(), "Sheet1!A3:B4");
  throws(() => r.getOffsetRange(-5, 0), "invalid");
  eq(r.getResizedRange(1, 1).getAddress(), "Sheet1!B2:D4");
  eq(r.getResizedRange(-1, 0).getAddress(), "Sheet1!B2:C2");
  eq(r.getAbsoluteResizedRange(1, 3).getAddress(), "Sheet1!B2:D2");
  eq(r.getLastCell().getAddress(), "Sheet1!C3");
  eq(r.getLastRow().getAddress(), "Sheet1!B3:C3");
  eq(r.getLastColumn().getAddress(), "Sheet1!C2:C3");
  eq(r.getRowsAbove().getAddress(), "Sheet1!B1:C1");
  eq(r.getRowsBelow(2).getAddress(), "Sheet1!B4:C5");
  eq(r.getColumnsBefore().getAddress(), "Sheet1!A2:A3");
  eq(r.getColumnsAfter(2).getAddress(), "Sheet1!D2:E3");
  eq(sheet.getRange("A1").getRangeEdge(ExcelScript.KeyboardDirection.down).getAddress(), "Sheet1!A4");
  eq(sheet.getRange("A1").getRangeEdge(ExcelScript.KeyboardDirection.right).getAddress(), "Sheet1!C1");
  eq(sheet.getRange("C4").getRangeEdge(ExcelScript.KeyboardDirection.up).getAddress(), "Sheet1!C1");
  eq(sheet.getRange("C4").getRangeEdge(ExcelScript.KeyboardDirection.left).getAddress(), "Sheet1!A4");
  eq(sheet.getRange("A1:B2").getRangeEdge(ExcelScript.KeyboardDirection.down, "B2").getAddress(), "Sheet1!B4");
  eq(sheet.getRange("A1").getExtendedRange(ExcelScript.KeyboardDirection.down).getAddress(), "Sheet1!A1:A4");
  eq(sheet.getRange("A2:C2").getExtendedRange(ExcelScript.KeyboardDirection.down).getAddress(), "Sheet1!A2:C4");
  eq(sheet.getRange("A2").getExtendedRange(ExcelScript.KeyboardDirection.right, sheet.getRange("A2")).getAddress(), "Sheet1!A2:C2");
  eq(sheet.getRange("B3").getSurroundingRegion().getAddress(), "Sheet1!A1:C4");
  eq(sheet.getUsedRange()?.getAddress(), "Sheet1!A1:C4");
  eq(sheet.getRange("B:B").getUsedRange()?.getAddress(), "Sheet1!B1:B4");
  eq(sheet.getRange("F:G").getUsedRange(), undefined);
  sheet.getRange("E6").getFormat().getFill().setColor("red");
  eq(sheet.getUsedRange()?.getAddress(), "Sheet1!A1:E6");
  eq(sheet.getUsedRange(true)?.getAddress(), "Sheet1!A1:C4");
  eq(sheet.getRange("D1:F9").getUsedRange(true), undefined);
  eq(sheet.getRange("D1:F9").getUsedRange()?.getAddress(), "Sheet1!E6");
  eq(r.getIntersection("C3:D9")?.getAddress(), "Sheet1!C3");
  eq(r.getIntersection(sheet.getRange("E1")), undefined);
  eq(r.getBoundingRect("E1").getAddress(), "Sheet1!B1:E3");
  eq(sheet.getRange().getCellCount(), 1048576 * 16384);
  eq(sheet.getRangeByIndexes(1, 1, 2, 2).getAddress(), "Sheet1!B2:C3");
  eq(sheet.getCell(3, 0).getValue(), "Pad");
  throws(() => sheet.getRange("nonsense!"), "invalid");
  throws(() => sheet.getRangeByIndexes(-1, 0, 1, 1), "invalid");
  eq(workbook.getSelectedRange().getAddress(), "Sheet1!B2:C3");
  eq(workbook.getActiveCell().getAddress(), "Sheet1!C3");
  const other = workbook.addWorksheet("My data");
  eq(other.getRange("A1:B2").getAddress(), "'My data'!A1:B2");
  eq(other.getUsedRange(), undefined);
  sheet.getRange("A2:A4").select();
  eq(workbook.getSelectedRange().getAddress(), "Sheet1!A2:A4");
  eq(workbook.getActiveCell().getAddress(), "Sheet1!A2");
}
