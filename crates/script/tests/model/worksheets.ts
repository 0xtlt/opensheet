function main(workbook: ExcelScript.Workbook) {
  const sheet = workbook.getActiveWorksheet();
  eq(sheet.getName(), "Sheet1");
  eq(workbook.getWorksheets().length, 1);
  const data = workbook.addWorksheet("Data");
  const other = workbook.addWorksheet();
  eq(workbook.getWorksheets().map(s => s.getName()), ["Sheet1", "Data", "Sheet3"]);
  eq(workbook.getWorksheet("data")?.getName(), "Data");
  eq(workbook.getWorksheet(data.getId())?.getName(), "Data");
  eq(workbook.getWorksheet("Nope"), undefined);
  eq(workbook.getFirstWorksheet().getName(), "Sheet1");
  eq(workbook.getLastWorksheet().getName(), "Sheet3");
  eq(workbook.getActiveWorksheet().getName(), "Sheet1");
  throws(() => workbook.addWorksheet("Data"), "already exists");
  throws(() => workbook.addWorksheet("a/b"), "invalid");
  other.setName("Last");
  throws(() => other.setName("Data"), "already exists");
  eq(other.getPosition(), 2);
  other.setPosition(0);
  eq(workbook.getWorksheets().map(s => s.getName()), ["Last", "Sheet1", "Data"]);
  eq(other.getNext()?.getName(), "Sheet1");
  eq(other.getPrevious(), undefined);
  eq(data.getNext(), undefined);
  eq(data.getPrevious()?.getName(), "Sheet1");
  const copy = sheet.copy(ExcelScript.WorksheetPositionType.after, data);
  eq(copy.getName(), "Sheet1 (2)");
  eq(copy.getPosition(), 3);
  eq(copy.getRange("A1").getValue(), 1);
  eq(sheet.copy().getPosition(), 0);
  eq(sheet.copy(ExcelScript.WorksheetPositionType.end).getPosition(), 5);
  eq(sheet.copy(ExcelScript.WorksheetPositionType.before, data).getPosition(), data.getPosition() - 1);
  other.delete();
  throws(() => other.getName(), "doesn't exist");
  eq(data.getName(), "Data");
  eq(workbook.getName(), "Budget.xlsx");
  data.activate();
  eq(workbook.getActiveWorksheet().getName(), "Data");
  eq(data.getVisibility(), ExcelScript.SheetVisibility.visible);
  data.setVisibility(ExcelScript.SheetVisibility.visible);
  // Hidden sheets: Last (0), Sheet1 copies and Data.
  const tabs = () => workbook.getWorksheets().filter(s => s.getVisibility() === ExcelScript.SheetVisibility.visible).length;
  const first = workbook.getFirstWorksheet();
  const last = workbook.getLastWorksheet();
  first.setVisibility(ExcelScript.SheetVisibility.hidden);
  last.setVisibility(ExcelScript.SheetVisibility.veryHidden);
  eq([first.getVisibility(), last.getVisibility()], ["Hidden", "VeryHidden"]);
  eq(tabs(), workbook.getWorksheets().length - 2);
  eq(workbook.getFirstWorksheet().getId(), first.getId());
  eq(workbook.getFirstWorksheet(true).getId(), first.getNext()?.getId());
  eq(workbook.getLastWorksheet(true).getId(), last.getPrevious()?.getId());
  eq(first.getNext(true)?.getId(), first.getNext()?.getId());
  eq(last.getPrevious()?.getNext(true), undefined);
  eq(first.getNext()?.getPrevious(true), undefined);
  throws(() => first.activate(), "hidden");
  // A hidden sheet is read and written like any other.
  first.getRange("A1").setValue(7);
  eq(first.getRange("A1").getValue(), 7);
  // Hiding the sheet in front brings the next tab in front.
  data.setVisibility(ExcelScript.SheetVisibility.hidden);
  eq(workbook.getActiveWorksheet().getId(), data.getNext(true)?.getId());
  data.setVisibility(ExcelScript.SheetVisibility.visible);
  data.activate();
  first.setVisibility(ExcelScript.SheetVisibility.visible);
  last.setVisibility(ExcelScript.SheetVisibility.hidden);
  eq(tabs(), workbook.getWorksheets().length - 1);
  eq(data.getTabColor(), "");
  data.setTabColor("orange");
  eq(data.getTabColor(), "#FFA500");
  data.setTabColor("");
  eq(data.getTabColor(), "");
  data.setTabColor("#0f0");
  eq(data.getShowGridlines(), true);
  data.setShowGridlines(false);
  eq(data.getShowGridlines(), false);
  eq(data.getShowHeadings(), true);
  data.setShowHeadings(false);
  eq(data.getShowHeadings(), false);
}
